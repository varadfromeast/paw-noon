    /// <summary>Why a display name was refused (wire names are the server's <c>reason</c> strings).</summary>
    public enum DisplayNameError { None, TooShort, TooLong, BadChars, Reserved }

    /// <summary>
    /// Player display names: 3-14 characters from A-Z, 0-9 and space after normalisation (trim, runs of spaces
    /// collapsed to one, ASCII a-z upper-cased). Guest names ("Stranger #1234") are generated by the server and
    /// are the only names with other characters. The server is the authority (profile-update); the client
    /// validates the same way so the keypad can say what is wrong before a round trip.
    /// </summary>
    public static class DisplayName
    {
        public const int MinLength = 3;
        public const int MaxLength = 14;

        /// <summary>Exact names nobody may take (house ghosts in supabase/seed.sql).</summary>
        private static readonly string[] ReservedExact = { "DUSTY", "MARSHAL MITTENS", "OLD TOM" };
        /// <summary>Names may not start with these (impersonating guests, staff, the game).</summary>
        private static readonly string[] ReservedPrefix = { "STRANGER", "ADMIN", "MODERATOR", "PAWNOON", "PAW NOON", "SUPPORT", "SYSTEM", "HOUSE GHOST" };

        /// <summary>A character the name keypad offers (and the server accepts): A-Z, 0-9, space.</summary>
        public static bool IsAllowedChar(char c)
        {
            return (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == ' ';
        }

        /// <summary>Trim spaces, collapse runs of spaces, ASCII a-z to A-Z. Other characters are kept (and refused later).</summary>
        public static string Normalize(string raw)
        {
            if (raw == null) return "";
            var sb = new StringBuilder(raw.Length);
            bool pendingSpace = false;
            for (int i = 0; i < raw.Length; i++)
            {
                char c = raw[i];
                if (c == ' ')
                {
                    if (sb.Length > 0) pendingSpace = true;
                    continue;
                }
                if (pendingSpace) { sb.Append(' '); pendingSpace = false; }
                if (c >= 'a' && c <= 'z') c = (char)(c - 32);
                sb.Append(c);
            }
            return sb.ToString();
        }

        /// <summary>
        /// Validates a name a player typed. On success <paramref name="normalized"/> is the name to store.
        /// Checks, in this order (same as the server): characters, length, reserved.
        /// </summary>
        public static DisplayNameError Validate(string raw, out string normalized)
        {
            normalized = Normalize(raw);
            for (int i = 0; i < normalized.Length; i++)
                if (!IsAllowedChar(normalized[i])) return DisplayNameError.BadChars;
            if (normalized.Length < MinLength) return DisplayNameError.TooShort;
            if (normalized.Length > MaxLength) return DisplayNameError.TooLong;
            for (int i = 0; i < ReservedExact.Length; i++)
                if (normalized == ReservedExact[i]) return DisplayNameError.Reserved;
            for (int i = 0; i < ReservedPrefix.Length; i++)
                if (normalized.StartsWith(ReservedPrefix[i], StringComparison.Ordinal)) return DisplayNameError.Reserved;
            return DisplayNameError.None;
        }

        public static bool IsValid(string raw)
        {
            string n;
            return Validate(raw, out n) == DisplayNameError.None;
        }

        /// <summary>Server reason string ("too_short", "too_long", "bad_chars", "reserved"); "" for None.</summary>
        public static string WireName(DisplayNameError e)
        {
            switch (e)
            {
                case DisplayNameError.TooShort: return "too_short";
                case DisplayNameError.TooLong: return "too_long";
                case DisplayNameError.BadChars: return "bad_chars";
                case DisplayNameError.Reserved: return "reserved";
                default: return "";
            }
        }

        public static DisplayNameError FromWire(string reason)
        {
            switch (reason)
            {
                case "too_short": return DisplayNameError.TooShort;
                case "too_long": return DisplayNameError.TooLong;
                case "bad_chars": return DisplayNameError.BadChars;
                case "reserved": return DisplayNameError.Reserved;
                default: return DisplayNameError.None;
            }
        }

        /// <summary>One short line for the keypad (bitmap-font safe).</summary>
        public static string Explain(DisplayNameError e)
        {
            switch (e)
            {
                case DisplayNameError.TooShort: return "AT LEAST 3 CHARACTERS";
                case DisplayNameError.TooLong: return "AT MOST 14 CHARACTERS";
                case DisplayNameError.BadChars: return "A-Z, 0-9 AND SPACES ONLY";
                case DisplayNameError.Reserved: return "THAT NAME IS TAKEN";
                default: return "";
            }
        }

        /// <summary>"STRANGER #0042" (what a guest is called before the server's profile is known).</summary>
        public static string GuestName(int number)
        {
            int n = number < 0 ? -number : number;
            return "STRANGER #" + (n % 10000).ToString("0000", CultureInfo.InvariantCulture);
        }

        /// <summary>A stable 0..9999 guest number from a user id (FNV-1a), so a guest keeps one name offline.</summary>
        public static int GuestNumber(string userId)
        {
            if (string.IsNullOrEmpty(userId)) return 0;
            uint h = 2166136261;
            for (int i = 0; i < userId.Length; i++)
            {
                h ^= userId[i];
                h *= 16777619;
            }
            return (int)(h % 10000);
        }

        /// <summary>Upper case and only the glyphs the bitmap fonts have (guest '#' kept), at most 16 chars.</summary>
        public static string ForDisplay(string s)
        {
            if (string.IsNullOrEmpty(s)) return "STRANGER";
            var sb = new StringBuilder(16);
            string u = s.Trim();
            for (int i = 0; i < u.Length && sb.Length < 16; i++)
            {
                char c = u[i];
                if (c >= 'a' && c <= 'z') c = (char)(c - 32);
                if (IsAllowedChar(c) || c == '#' || c == '-' || c == '\'' || c == '.') sb.Append(c);
            }
            string r = sb.ToString().Trim();
            return r.Length == 0 ? "STRANGER" : r;
        }
    }

    /// <summary>The <c>user</c> object of a Supabase Auth (GoTrue) session: who it is and how it signs in.</summary>
    public sealed class AuthUserInfo
    {
        public string Id = "";
        public bool IsAnonymous = true;
        /// <summary>Linked providers other than "anonymous", e.g. {"apple"}.</summary>
        public string[] Providers = new string[0];
        /// <summary>Unix seconds, 0 when unknown.</summary>
        public long CreatedAt;

        public bool HasProvider(string p)
        {
            for (int i = 0; i < Providers.Length; i++) if (Providers[i] == p) return true;
            return false;
        }

        /// <summary>Linked to Apple or Google (the M5 ranked rule and the server's hasLinkedIdentity).</summary>
        public bool IsLinked { get { return !IsAnonymous && (HasProvider("apple") || HasProvider("google")); } }

        /// <summary>
        /// Reads <c>{id, is_anonymous, created_at, identities:[{provider}], app_metadata:{provider, providers:[]}}</c>.
        /// Null when there is no id.
        /// </summary>
        public static AuthUserInfo Parse(object user)
        {
            string id = PnJson.Str(user, "id", "");
            if (string.IsNullOrEmpty(id)) return null;
            var u = new AuthUserInfo();
            u.Id = id;
            var list = new List<string>(2);
            var ids = PnJson.Arr(user, "identities");
            if (ids != null)
                for (int i = 0; i < ids.Count; i++) AddProvider(list, PnJson.Str(ids[i], "provider", ""));
            var meta = PnJson.Obj(user, "app_metadata");
            var mp = PnJson.Arr(meta, "providers");
            if (mp != null)
                for (int i = 0; i < mp.Count; i++) AddProvider(list, mp[i] as string);
            AddProvider(list, PnJson.Str(meta, "provider", ""));
            u.Providers = list.ToArray();
            // older Auth versions have no is_anonymous: anonymous = no real identity
            u.IsAnonymous = PnJson.Has(user, "is_anonymous") ? PnJson.Bool(user, "is_anonymous", true) : list.Count == 0;
            u.CreatedAt = ParseIsoUnix(PnJson.Str(user, "created_at", null));
            return u;
        }

        private static void AddProvider(List<string> list, string p)
        {
            if (string.IsNullOrEmpty(p) || p == "anonymous" || p == "email" || list.Contains(p)) return;
            list.Add(p);
        }

        public static long ParseIsoUnix(string iso)
        {
            if (string.IsNullOrEmpty(iso)) return 0;
            DateTimeOffset t;
            if (DateTimeOffset.TryParse(iso, CultureInfo.InvariantCulture, DateTimeStyles.AssumeUniversal | DateTimeStyles.AdjustToUniversal, out t))
                return t.ToUnixTimeSeconds();
            return 0;
        }

        /// <summary>Comma-separated providers (PlayerPrefs).</summary>
        public static string Join(string[] p) { return p == null ? "" : string.Join(",", p); }

        public static string[] Split(string csv)
        {
            if (string.IsNullOrEmpty(csv)) return new string[0];
            return csv.Split(new[] { ',' }, StringSplitOptions.RemoveEmptyEntries);
        }
    }

    /// <summary>What happened to a link attempt (SupabaseAuth.LinkApple / LinkGoogle).</summary>
    public enum LinkOutcome
    {
        /// <summary>The identity is now on this same user (id unchanged: bounty, MMR, matches stay).</summary>
        Linked,
        /// <summary>That Apple / Google account already belongs to another player (another phone). Offer to switch.</summary>
        IdentityTaken,
        /// <summary>The server ignored link_identity and made a brand-new user: Auth too old or linking off. Nothing stored.</summary>
        LinkUnsupported,
        /// <summary>The player closed the Apple / Google sheet.</summary>
        Cancelled,
        /// <summary>No network / server down.</summary>
        Offline,
        /// <summary>Native sign-in is not available on this device / build (no SDK, no client id).</summary>
        Unavailable,
        /// <summary>Anything else (bad token, provider disabled, ...): see the code.</summary>
        Failed
    }

    /// <summary>A GoTrue error body: <c>{code, error_code, msg}</c> (new) or <c>{error, error_description}</c> (old).</summary>
    public struct AuthError
    {
        public int Status;
        public string Code;
        public string Message;

        public static AuthError Parse(long status, string json)
        {
            var e = new AuthError();
            e.Status = (int)status;
            var o = PnJson.ParseObject(json);
            e.Code = PnJson.Str(o, "error_code", null);
            if (string.IsNullOrEmpty(e.Code)) e.Code = PnJson.Str(o, "error", null);
            e.Message = PnJson.Str(o, "msg", null) ?? PnJson.Str(o, "message", null) ?? PnJson.Str(o, "error_description", "") ?? "";
            if (string.IsNullOrEmpty(e.Code)) e.Code = "http_" + status.ToString(CultureInfo.InvariantCulture);
            return e;
        }

        /// <summary>The identity is already attached to a different user.</summary>
        public bool IdentityTaken
        {
            get
            {
                if (Code == "identity_already_exists") return true;
                string m = Message ?? "";
                return Status == 422 && m.IndexOf("already", StringComparison.OrdinalIgnoreCase) >= 0 &&
                       (m.IndexOf("identity", StringComparison.OrdinalIgnoreCase) >= 0 || m.IndexOf("linked", StringComparison.OrdinalIgnoreCase) >= 0);
            }
        }
    }

    /// <summary>Decides what a 200 from the id-token grant means for a link (pure, unit-tested).</summary>
    public static class LinkAnswer
    {
        /// <summary>A user created this recently by the grant itself is "new" (the link flag was ignored).</summary>
        public const long FreshUserSeconds = 120;

        /// <summary>
        /// <paramref name="guestId"/>: the user that asked to link. <paramref name="user"/>: the session's user.
        /// Same id = Linked. Different id and created just now = LinkUnsupported (the server signed the token in as a
        /// new account instead of linking; do not keep that session). Different older id = IdentityTaken (that Apple /
        /// Google account already has its own player; the session may be adopted if the player chooses to switch).
        /// </summary>
        public static LinkOutcome Classify(string guestId, AuthUserInfo user, long nowUnix)
        {
            if (user == null) return LinkOutcome.Failed;
            if (string.IsNullOrEmpty(guestId) || user.Id == guestId) return LinkOutcome.Linked;
            if (user.CreatedAt > 0 && nowUnix - user.CreatedAt <= FreshUserSeconds) return LinkOutcome.LinkUnsupported;
            return LinkOutcome.IdentityTaken;
        }
    }

    /// <summary>
    /// Answer of <c>POST /profile-read</c> and <c>/profile-update</c> (supabase/functions/_shared/schemas/profile.response.schema.json).
    /// Stats are server-validated PvP matches only (the profiles counters written by match-submit).
    /// </summary>
    public sealed class ProfileInfo
    {
        public string UserId = "";
        public string DisplayName = "";
        public string Character = "whiskers";
        public bool IsGuest = true;
        public string[] Providers = new string[0];
        public int Matches;
        public int Wins;
        /// <summary>-1 when there is none.</summary>
        public long BestReactionNs = -1;
        public int Lightning;
        public int Mmr = 1200;
        public bool Rated;
        public int Coins;
        public int DailyStreak;
        public string[] OwnedItems = new string[0];

        public int WinPercent { get { return Matches > 0 ? (int)Math.Round(100.0 * Wins / Matches) : 0; } }

        /// <summary>Null on anything malformed.</summary>
        public static ProfileInfo Parse(string json, out string error)
        {
            error = null;
            var root = PnJson.ParseObject(json);
            if (root == null) { error = "not a JSON object"; return null; }
            var p = new ProfileInfo();
            p.UserId = PnJson.Str(root, "userId", "");
            p.DisplayName = PnJson.Str(root, "displayName", null);
            if (string.IsNullOrEmpty(p.DisplayName)) { error = "missing displayName"; return null; }
            p.Character = PnJson.Str(root, "character", "whiskers");
            p.IsGuest = PnJson.Bool(root, "isGuest", true);
            p.Providers = Strings(PnJson.Arr(root, "providers"));
            var s = PnJson.Obj(root, "stats");
            p.Matches = Math.Max(0, PnJson.Int(s, "matches", 0));
            p.Wins = Math.Max(0, Math.Min(p.Matches, PnJson.Int(s, "wins", 0)));
            double best = PnJson.Num(s, "bestReactionNs", -1);
            p.BestReactionNs = best > 0 ? (long)best : -1;
            p.Lightning = Math.Max(0, PnJson.Int(s, "lightning", 0));
            var r = PnJson.Obj(root, "rating");
            p.Rated = r != null && PnJson.Int(r, "matches", 0) > 0;
            p.Mmr = r != null ? PnJson.Int(r, "mmr", 1200) : 1200;
            p.Coins = Math.Max(0, PnJson.Int(root, "coins", 0));
            p.DailyStreak = Math.Max(0, PnJson.Int(root, "dailyStreak", 0));
            p.OwnedItems = Strings(PnJson.Arr(root, "ownedItems"));
            return p;
        }

        private static string[] Strings(List<object> a)
        {
            if (a == null) return new string[0];
            var l = new List<string>(a.Count);
            for (int i = 0; i < a.Count; i++) { var s = a[i] as string; if (!string.IsNullOrEmpty(s)) l.Add(s); }
            return l.ToArray();
        }

        /// <summary>Best reaction for the card: the lower of the server's and the device's (solo) best; -1 = none.</summary>
        public static long CombinedBest(ProfileInfo p, long localBestNs)
        {
            long a = p != null ? p.BestReactionNs : -1;
            long b = localBestNs > 0 ? localBestNs : -1;
            if (a <= 0) return b;
            if (b <= 0) return a;
            return Math.Min(a, b);
        }
    }

    /// <summary>A boolean that survives restarts (PlayerPrefs in the game, a dictionary in tests).</summary>
    public interface IFlagStore
    {
        bool Get(string key);
        void Set(string key, bool value);
    }

    /// <summary>
    /// "KEEP YOUR BOUNTY" is offered once (SPEC_V2 §5, D5): after the first finished solo match, to a player who
    /// is not linked yet, when accounts can work at all (online configured, or the Editor mock). Shown = spent,
    /// whatever the player picks (LATER included); the same sheet stays reachable from Settings > ACCOUNT.
    /// </summary>
    public sealed class BountyGate
    {
        public const string Key = "pn_bounty_offered";
        private readonly IFlagStore store;

        public BountyGate(IFlagStore store) { this.store = store; }

        public bool Offered { get { return store.Get(Key); } }

        public bool ShouldOffer(bool soloMatchFinished, bool linked, bool accountsAvailable)
        {
            return soloMatchFinished && !linked && accountsAvailable && !store.Get(Key);
        }

        /// <summary>Call when the sheet is actually shown.</summary>
        public void MarkOffered() { store.Set(Key, true); }

        /// <summary>Account deleted / review reset: the next first solo match offers it again.</summary>
        public void Reset() { store.Set(Key, false); }
    }
