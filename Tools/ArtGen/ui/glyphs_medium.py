"""Hand-drawn glyphs for font_medium: bold 7 px cap height, 2 px stems, x-height 5, descender 2.
Each entry: char -> (oy, rows). oy = rows from the top of the line (cap top = 0, baseline = 7).
'#' = ink, '.' = empty. Digits are tabular (all 5 wide).
"""

G = {}


def g(ch, oy, rows):
    rows = [r for r in rows.split()]
    w = len(rows[0])
    assert all(len(r) == w for r in rows), (ch, rows)
    G[ch] = (oy, rows)


